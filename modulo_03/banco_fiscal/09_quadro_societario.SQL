USE curso_integridade_fiscal;
GO
SET NOCOUNT ON;
GO

DROP TABLE IF EXISTS dbo.socio_administrador;
GO

CREATE TABLE dbo.socio_administrador (
    id_socio          INT           NOT NULL,
    id_contribuinte   INT           NOT NULL,
    nome              VARCHAR(120)  NOT NULL,   -- caixa e espacos irregulares, de proposito
    cpf               VARCHAR(14)   NOT NULL,   -- formatos heterogeneos, de proposito
    qualificacao      VARCHAR(40)   NOT NULL,
    data_entrada      DATE          NOT NULL,
    participacao_pct  DECIMAL(5,2)  NULL,
    telefone          VARCHAR(20)   NULL,
    CONSTRAINT PK_socio_administrador  PRIMARY KEY (id_socio),
    CONSTRAINT FK_socio_contribuinte   FOREIGN KEY (id_contribuinte)
        REFERENCES dbo.contribuinte (id_contribuinte),
    CONSTRAINT CK_socio_qualificacao   CHECK (qualificacao IN ('SOCIO ADMINISTRADOR','SOCIO',
                                              'ADMINISTRADOR','PRESIDENTE','DIRETOR')),
    CONSTRAINT CK_socio_participacao   CHECK (participacao_pct IS NULL
                                              OR (participacao_pct > 0 AND participacao_pct <= 100))
);
GO

CREATE INDEX IX_socio_contribuinte ON dbo.socio_administrador (id_contribuinte);
GO

