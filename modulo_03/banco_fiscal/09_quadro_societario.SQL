   ATENCAO DIDATICA: a coluna cpf e VARCHAR e NAO tem restricao de
   formato. Isso e proposital. O CPF aparece aqui exatamente como costuma
   chegar das bases de origem: com mascara, sem mascara, com espacos, com
   mascara parcial e - o caso mais traicoeiro - com o zero a esquerda
